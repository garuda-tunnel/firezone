#!/usr/bin/env bash
# Regenerates fixtures.env from the upstream image firezone/firezone:0.7.36.
#
# The fixtures pin cross-version compatibility of formats stored outside the
# image (Review Focus 1 of the vendored-build plan):
#   - a Cloak AES.GCM.V1 ciphertext produced by upstream 0.7.36 with a fixed
#     test DATABASE_ENCRYPTION_KEY: the new image must still decrypt it
#     (cloak/cloak_ecto bump, T8);
#   - an argon2 password hash produced the way FzHttp.Crypto.hash/1 does it
#     (Argon2.hash_pwd_salt/1, default opts): the new image must still verify
#     it (argon2_elixir).
#
# All values below are TEST-ONLY: the key is generated, published here, and
# guards no real data.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${1:-$SCRIPT_DIR/fixtures.env}"

# Fixed test key (openssl rand -base64 32). Generated once; committed on
# purpose so check.sh reproduces against any image without regenerating.
FIXTURE_DATABASE_ENCRYPTION_KEY="4kFXwA2+1hG8Uq7wIwZIfVKPbS/QIsa2DzH7C1sFECM="
FIXTURE_PLAINTEXT="garuda-compat-fixture-plaintext-v1"
FIXTURE_PASSWORD="garuda-compat-fixture-password-v1"

# Upstream image to generate from. runtime.exs validates config at boot, even
# for `eval`, so the eval gets dummy DATABASE_*/EXTERNAL_URL values (they are
# never used: nothing connects to the DB and the Vault is started by hand).
# SAML cert/key files must exist (validate_file), so a temp dir is mounted at
# /var/firezone and populated with a throwaway self-signed cert first.
UPSTREAM_IMAGE="firezone/firezone:0.7.36"

workdir="$(mktemp -d)"
trap 'rm -rf "$workdir"' EXIT

# Eval expression is passed through the mounted dir: quoting it through both
# docker and sh would be fragile.
cat >"$workdir/expr.exs" <<'EOF'
{:ok, _pid} = FzHttp.Vault.start_link()
{:ok, ciphertext} = FzHttp.Vault.encrypt(System.fetch_env!("FIXTURE_PLAINTEXT"))
hash = FzHttp.Crypto.hash(System.fetch_env!("FIXTURE_PASSWORD"))
# Cloak ciphertexts are raw binaries (IV/tag bytes); base64 keeps fixtures.env ASCII.
IO.puts("CIPHERTEXT_B64=" <> Base.encode64(ciphertext))
IO.puts("ARGON2_HASH=" <> hash)
EOF

# Dummy secret values: valid base64, >= 64 (SKB) / 8 (salt) decoded bytes.
SKB="Z2FydWRhLWNvbXBhdC1maXh0dXJlLXNlY3JldC1rZXktYmFzZS1sb25nLWVub3VnaC1mb3ItcGhvZW5peC12YWxpZGF0aW9uLWNoZWNr"
SALT="Z2FydWRhLWNvbXBhdC1maXh0dXJlLXNhbHQ="

docker run --rm \
  -e EXTERNAL_URL="http://localhost:13000" \
  -e DATABASE_HOST="127.0.0.1" \
  -e DATABASE_NAME="firezone_fixture" \
  -e DATABASE_USER="firezone_fixture" \
  -e DATABASE_PASSWORD="fixture" \
  -e DATABASE_ENCRYPTION_KEY="$FIXTURE_DATABASE_ENCRYPTION_KEY" \
  -e GUARDIAN_SECRET_KEY="$FIXTURE_DATABASE_ENCRYPTION_KEY" \
  -e SECRET_KEY_BASE="$SKB" \
  -e LIVE_VIEW_SIGNING_SALT="$SALT" \
  -e COOKIE_SIGNING_SALT="$SALT" \
  -e COOKIE_ENCRYPTION_SALT="$SALT" \
  -e FIXTURE_PLAINTEXT="$FIXTURE_PLAINTEXT" \
  -e FIXTURE_PASSWORD="$FIXTURE_PASSWORD" \
  -v "$workdir:/var/firezone" \
  --entrypoint sh \
  "$UPSTREAM_IMAGE" -c '
    set -e
    openssl req -x509 -sha256 -nodes -days 365 -newkey rsa:2048 \
      -keyout /var/firezone/saml.key -out /var/firezone/saml.crt \
      -subj "/CN=fixture" >/dev/null 2>&1
    exec /app/bin/firezone eval "$(cat /var/firezone/expr.exs)"
  ' | tee "$workdir/eval.out"

ciphertext_b64="$(sed -n 's/^CIPHERTEXT_B64=//p' "$workdir/eval.out" | tail -1)"
argon2_hash="$(sed -n 's/^ARGON2_HASH=//p' "$workdir/eval.out" | tail -1)"

[[ -n "$ciphertext_b64" ]] || { echo "make-fixtures: no ciphertext in eval output" >&2; exit 1; }
[[ -n "$argon2_hash" ]] || { echo "make-fixtures: no argon2 hash in eval output" >&2; exit 1; }

# Values are single-quoted: the argon2 hash contains '$' parameter separators
# that double quotes would expand at `source` time.
cat >"$OUT" <<EOF
# Generated by kube/image/compat/make-fixtures.sh from $UPSTREAM_IMAGE.
# TEST-ONLY values: generated key, known plaintext/password. Never real secrets.
# FIXTURE_CIPHERTEXT_B64 is base64(Cloak AES.GCM.V1 ciphertext of FIXTURE_PLAINTEXT).
export FIXTURE_DATABASE_ENCRYPTION_KEY='$FIXTURE_DATABASE_ENCRYPTION_KEY'
export FIXTURE_PLAINTEXT='$FIXTURE_PLAINTEXT'
export FIXTURE_PASSWORD='$FIXTURE_PASSWORD'
export FIXTURE_CIPHERTEXT_B64='$ciphertext_b64'
export FIXTURE_ARGON2_HASH='$argon2_hash'
EOF

echo "wrote $OUT"
